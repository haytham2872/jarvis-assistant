"""Goals (docs/archive/GOALS-ROADMAP.md G1b): the one-way vault mirror, and indexing a done result.

SQLite is the only authority for a goal. So the owner can read one in Obsidian, code writes a
generated copy to `jarvis-vault/goals/<goal_id>-<slug>/`:

* `plan.md` (requirements and milestones with their state), `notes.md`, `sources.md` (the
  evidence index), and every goal file at its latest revision. Each opens with a line saying
  it is generated and that changes go through JARVIS.
* Plain file writes, the way `drafts/listening-log.md` is written: never `vault_write`, never
  seen by the reconcile pass (whose folder list does not include `goals/`), never indexed.
  Unfinished goal material therefore cannot reach semantic recall.
* A hand edit is never overwritten and never imported: `.mirror.json` keeps the hash of each
  file as last written; a file on disk that no longer matches is kept, and the new render goes
  beside it (`name (2).md`), with a log line.

A done goal's `result.md` is the one thing indexed, once per (goal, revision), dated and with
its sources (`index_result`). Partial, cancelled and failed goals are never indexed.
"""
from __future__ import annotations
from backend import localtime as _localtime
from backend import owner as _owner

import datetime as _dt
import hashlib
import json
import logging
from pathlib import Path
from zoneinfo import ZoneInfo

from backend.storage import goals as store

log = logging.getLogger(__name__)

_TZ = _localtime.ZONE
FOLDER = "goals"
_MANIFEST = ".mirror.json"
GENERATED = ("<!-- Generated by JARVIS from goal {gid}. Edits here are not read back: "
             "tell JARVIS what to change. -->\n\n")


def _root() -> Path:
    from backend.tools import vault
    return Path(vault._VAULT) / FOLDER


def _sha(text: str) -> str:
    return hashlib.sha256(text.encode("utf-8")).hexdigest()


def _day(ts) -> str:
    return _dt.datetime.fromtimestamp(ts, _TZ).strftime("%Y-%m-%d") if ts else "none"


def render(goal_id: str) -> dict[str, str]:
    """{file name: content} for the goal's folder, from the records. Pure reads."""
    g = store.get(goal_id)
    if g is None:
        return {}
    head = GENERATED.format(gid=goal_id)
    plan = [f"# {g['title']}", "", f"Goal {goal_id} -- state: {g['state']}, created "
            f"{_day(g['created_at'])}, deadline {_day(g.get('deadline_at'))}.", "",
            _owner.say(f"«His» words: {g['authorized_words']}"), "", "## Requirements"]
    plan += [f"- {c['criterion_id']}: {c['text']}" for c in store.active_criteria(g)]
    plan += ["", "## Milestones"]
    plan += [f"- {m['milestone_id']} [{m['state']}] {m['title']} -> {m['expected']}"
             for m in store.plan(goal_id)] or ["(not planned yet)"]
    if g["state"] in store.ENDED and g["outcome"].get("reason"):
        plan += ["", f"Ended: {g['outcome']['reason']}"]
    notes = ["# Notes", ""]
    for section in store.NOTE_SECTIONS:
        items = [n for n in store.notes(goal_id) if n["section"] == section]
        if items:
            notes += [f"## {section}"] + [
                f"- {n['body']}" + (f" [{', '.join(n['evidence_ids'])}]" if n["evidence_ids"] else "")
                for n in items] + [""]
    sources = ["# Sources", "", "Captured tool results this goal relies on (full text in goal storage).", ""]
    for e in store.evidence_index(goal_id):
        args = json.loads(e["arguments_json"] or "{}")
        what = args.get("url") or args.get("task") or args.get("query") or ""
        sources.append(f"- {e['evidence_id']} · {e['tool']} · {str(what)[:160]} · captured "
                       f"{e['local_date']} · {e['chars']:,} chars")
    out = {"plan.md": head + "\n".join(plan) + "\n",
           "notes.md": head + "\n".join(notes) + "\n",
           "sources.md": head + "\n".join(sources) + "\n"}
    for f in store.files(goal_id):
        if f["name"] in out:
            continue                              # a goal file never replaces a generated view
        body = store.read_file(goal_id, f["name"])["body"] or ""
        out[f["name"]] = (head + body) if f["name"].endswith(".md") else body
    return out


def _manifest(folder: Path) -> dict:
    try:
        return json.loads((folder / _MANIFEST).read_text(encoding="utf-8"))
    except Exception:
        return {}


def _target(folder: Path, name: str, manifest: dict) -> Path:
    """`name`, or the first `name (n)` beside it that is free or still ours."""
    stem, dot, ext = name.rpartition(".")
    candidates = [name] + [f"{stem} ({n}).{ext}" if dot else f"{name} ({n})" for n in range(2, 50)]
    for cand in candidates:
        path = folder / cand
        if not path.exists():
            return path
        try:
            if _sha(path.read_text(encoding="utf-8")) == manifest.get(cand):
                return path                       # unchanged since we wrote it: ours to replace
        except Exception:
            continue
    return folder / candidates[-1]


def mirror(goal_id: str) -> int:
    """Write the goal's folder. Returns how many files changed. Never raises."""
    try:
        g = store.get(goal_id)
        if g is None:
            return 0
        folder = _root() / g["folder"]
        folder.mkdir(parents=True, exist_ok=True)
        manifest = _manifest(folder)
        changed = 0
        for name, content in render(goal_id).items():
            path = _target(folder, name, manifest)
            if path.name != name and (folder / name).exists():
                log.info("goals: %s/%s was edited by hand; kept, new render in %s",
                         g["folder"], name, path.name)
            if path.exists() and path.read_text(encoding="utf-8") == content:
                manifest[path.name] = _sha(content)
                continue
            path.write_text(content, encoding="utf-8")
            manifest[path.name] = _sha(content)
            changed += 1
        (folder / _MANIFEST).write_text(json.dumps(manifest, indent=1), encoding="utf-8")
        _note_mirrored(goal_id, manifest)
        return changed
    except Exception as exc:
        log.warning("goals: mirror of %s failed (%s)", goal_id, exc)
        return 0


def _note_mirrored(goal_id: str, manifest: dict) -> None:
    """goal_files.mirrored_hash: the hash of the vault copy last written for that revision."""
    from backend.storage import db
    conn = db.connect()
    if conn is None:
        return
    with conn:
        for f in store.files(goal_id):
            h = manifest.get(f["name"])
            if h:
                conn.execute("UPDATE goal_files SET mirrored_hash=? WHERE goal_id=? AND name=?"
                             " AND revision=?", (h, goal_id, f["name"], f["revision"]))


async def index_result(goal_id: str) -> bool:
    """Index a DONE goal's result.md once per revision, dated, sources kept. Only done goals:
    a partial, cancelled or failed one has not passed its checks."""
    g = store.get(goal_id)
    if g is None or g["state"] != store.DONE:
        return False
    f = store.read_file(goal_id, "result.md")
    if f is None or not (f["body"] or "").strip():
        return False
    key = f"indexed:result.md:{f['revision']}"
    if store.has_event(goal_id, key):
        return False
    content = (f"# Goal result: {g['title']}\n\nDone {_day(g.get('ended_at'))} (goal {goal_id}). "
               f"Figures are as of that date.\n\n{f['body']}")
    try:
        from backend.brain import semindex
        n = await semindex.index_file(FOLDER, f"{g['folder']}.md", content)
    except Exception as exc:
        log.warning("goals: result of %s not indexed (%s)", goal_id, exc)
        return False
    if n:
        store.record_event(goal_id, "indexed", {"revision": f["revision"], "chunks": n}, key)
    return bool(n)
