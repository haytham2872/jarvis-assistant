def test_writer_shapes_dates_links_and_goal_titles():
    profile("Will Turner", aliases=["Captain Turner"])
    note("people", "owner.md", "# Sam\n\nAn evolving portrait, not a profile.")
    note("people", "_template.md", "# Template")
    note("people", "predictions.md", "# Prediction scoreboard")
    note("topics", "duration.md", "---\nlast_researched: 2026-10-17\nlast_angle: deepen\n---\n# Duration\n\nWill asked about [[people/Sam|the portrait]] and [[missing]].")
    note("skills", "check-rates.md", skills.render(skills.Skill(name="check-rates", description="Check the ECB before a news report", body="# Check rates\n\nRead [[duration]].", created="2026-09-16")))
    note("letters", "2026-10-01_8f3b162a.md", "Dear future self,\n\nKeep the question about [[topics/duration]] open.")
    note("conversations/significant", "2026-10-02_8f3b162a.md", "We separated price from value. [[Duration|the question]] remains.")
    note("creative", "listening.md", "# Listening\n\nA short composition about Will Turner.")
    note("self", "positions.md", positions.render_file({"duration": positions.Position(topic="Duration", stance="Price and value differ.", sources="[[topics/duration]], [[letters/2026-10-01_8f3b162a]]", formed="2026-09-21", revisions=["2026-10-17 — separated liquidity from duration"])}))
    note("self", "ruminations.md", "# Excluded")
    note("drafts", "hidden.md", "# Excluded")
    g = goal(G.PARTIAL, title="Compare euro bond funds")
    note("goals", g["folder"] + "/result.md", "<!-- Generated by JARVIS from goal -->\n\n# A model's different title\n\n[[Duration]]")
    for name in ("plan.md", "notes.md", "sources.md", "plan (2).md", "result (2).md"):
        note("goals", g["folder"] + "/" + name, "# Excluded")
    v = M.view(); nodes = {n["id"]: n for n in v["nodes"]}
    assert v["complete"] and len(nodes) == 9 and not v["truncated"]
    assert nodes["topics/duration.md"]["created_source"] == "modified"
    assert nodes["topics/duration.md"]["created"] == 1792300800  # never last_researched
    assert nodes["letters/2026-10-01_8f3b162a.md"]["created"] == M._date("2026-10-01")
    assert nodes["self/positions.md#Duration"]["created"] == M._date("2026-09-21")
    assert nodes["skills/check-rates.md"]["created"] == M._date("2026-09-16")
    assert nodes[f"goals/{g['folder']}/result.md"]["title"] == g["title"]
    assert nodes[f"goals/{g['folder']}/result.md"]["state"] == "partial"
    assert any(e["kind"] == "mention" and e["a"] == "people/WillTurner.md" for e in v["edges"])
    assert any("self/positions.md#Duration" in (e["a"], e["b"]) for e in v["edges"])
    assert any({e["a"], e["b"]} == {"letters/2026-10-01_8f3b162a.md", "topics/duration.md"} for e in v["edges"])
    assert any({e["a"], e["b"]} == {f"goals/{g['folder']}/result.md", "topics/duration.md"} for e in v["edges"])
    assert len({(e["a"], e["b"]) for e in v["edges"]}) == len(v["edges"])
    assert all(notes.read(**n["link"])["text"] for n in nodes.values())


