def test_a_failed_read_is_retried_even_when_nothing_changed(monkeypatch):
    note("topics", "fine.md", "# Fine")
    note("topics", "flaky.md", "# Flaky")
    real, calls = M._parse, []
    def flaky(folder, name, *a):
        calls.append(name)
        if name == "flaky.md" and calls.count("flaky.md") == 1:
            raise OSError("transient read error")
        return real(folder, name, *a)
    monkeypatch.setattr(M, "_parse", flaky)
    first = M.view()
    assert not first["complete"] and len(first["nodes"]) == 1
    second = M.view()
    assert second["complete"] and len(second["nodes"]) == 2


