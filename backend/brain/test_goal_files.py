def _folder(world_tmp_vault, g):
    return world_tmp_vault / "goals" / S.get(g["goal_id"])["folder"]


def _vault():
    from backend.tools import vault
    from pathlib import Path
    return Path(vault._VAULT)


# --- the mirror -------------------------------------------------------------------------

def test_a_done_goal_is_mirrored_without_vault_write_or_indexing_its_drafts(world, indexed, monkeypatch):
    from backend.tools import vault

    async def no_vault_write(*a, **k):
        raise AssertionError("the mirror went through vault_write")
    monkeypatch.setattr(vault, "vault_write", no_vault_write)
    g = _start()
    run(_cycles())
    folder = _folder(_vault(), g)
    names = sorted(p.name for p in folder.iterdir())
    assert {"plan.md", "notes.md", "sources.md", "result.md"} <= set(names)
    assert (folder / "result.md").read_text(encoding="utf-8").startswith("<!-- Generated by JARVIS")
    # only the done result was indexed, once, as the goals/<folder>.md result
    assert [(c[0], c[1]) for c in indexed] == [("goals", f"{S.get(g['goal_id'])['folder']}.md")]
    assert "0.07%" in indexed[0][2] and "Done" in indexed[0][2]


def test_a_hand_edited_file_is_kept_and_the_new_render_goes_beside_it(world, indexed):
    g = _start()
    run(_cycles(1))                                   # planned: plan.md written
    folder = _folder(_vault(), g)
    plan = folder / "plan.md"
    plan.write_text("my own notes on this plan", encoding="utf-8")
    run(_cycles())                                    # the goal moves on and is mirrored again
    assert plan.read_text(encoding="utf-8") == "my own notes on this plan"
    beside = folder / "plan (2).md"
    assert beside.exists() and "[done]" in beside.read_text(encoding="utf-8")
    F.mirror(g["goal_id"])                            # a later render reuses (2), not (3)
    assert not (folder / "plan (3).md").exists()


def test_partial_and_cancelled_goals_are_never_indexed(world, indexed):
    g = _start()
    run(_cycles(1))
    S.save_file(g["goal_id"], "M1", 1, name="result.md", content="draft", expected_revision=None,
                op_key="x")
    S.transition(g["goal_id"], S.PARTIAL, expect=(S.ACTIVE,))
    assert run(F.index_result(g["goal_id"])) is False
    g2 = _start(title="Other")
    S.transition(g2["goal_id"], S.CANCELLED, expect=(S.ACTIVE,))
    assert run(F.index_result(g2["goal_id"])) is False
    assert [c for c in indexed if c[0] == "goals"] == []


def test_a_done_result_is_indexed_once_per_revision(world, indexed):
    g = _start()
    run(_cycles())
    assert S.get(g["goal_id"])["state"] == S.DONE
    before = len(indexed)
    assert run(F.index_result(g["goal_id"])) is False          # already indexed
    assert len(indexed) == before


