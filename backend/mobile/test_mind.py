def test_letter_budget_protects_topics_and_keeps_old_linked_letters():
    for i in range(95): note("topics", f"topic-{i}.md", f"# Topic {i}")
    profile("Will Turner")
    start = datetime(2025, 1, 1)
    for i in range(460):
        name = f"{(start + timedelta(days=i)).date()}_{i:08x}.md"
