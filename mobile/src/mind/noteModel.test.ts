import { noteBlocks, noteTitle } from './noteModel';

it('parses existing Markdown with cross-block reference links and a title', () => {
  const text = '# Duration\n\nSee [the ECB][ecb].\n\n[ecb]: https://www.ecb.europa.eu/\n';
  const blocks = noteBlocks(text);
  expect(blocks).toHaveLength(2); expect(JSON.stringify(blocks[1])).toContain('https://www.ecb.europa.eu/');
  expect(noteTitle(text, 'duration.md')).toBe('Duration'); expect(noteTitle('', 'bond-prices.md')).toBe('bond prices');
});
it('keeps stored frontmatter out of the reading surface', () => {
  const blocks = noteBlocks('---\ncreated: 2026-10-24\nlast_researched: 2026-10-25\n---\n# Bond prices\n\nA sourced distinction.');
  expect(blocks).toHaveLength(2); expect(JSON.stringify(blocks)).not.toContain('last_researched');
  expect(blocks[0]).toMatchObject({ type: 'heading', text: 'Bond prices' });
});
it('keeps a 60,000 character note in small virtualizable blocks without losing text', () => {
  const text = 'A sourced observation about duration and changing yields. '.repeat(1100).slice(0, 60000);
  const blocks = noteBlocks(text);
  expect(blocks.length).toBeGreaterThan(20); expect(blocks.every((b) => 'text' in b && b.text.length <= 2400)).toBe(true);
  expect(blocks.map((b) => 'text' in b ? b.text : '').join('')).toBe(text);
});
it('chunks code, lists with their numbering and table rows rather than mounting all at once', () => {
  const code = noteBlocks('```text\n' + 'x'.repeat(59000) + '\n```');
  expect(code.length).toBeGreaterThan(20); expect(code.every((b) => b.type === 'code' && b.text.length <= 2400)).toBe(true);
  const lists = noteBlocks(Array.from({ length: 40 }, (_, i) => `${i + 1}. observation ${i}`).join('\n'));
  expect(lists).toHaveLength(4); expect(lists[1]).toMatchObject({ type: 'list', start: 13 });
  const table = noteBlocks('| Month | Brier |\n| --- | --- |\n' + '| Oct | .192 |\n'.repeat(40));
  expect(table).toHaveLength(4); expect(table[0]).toMatchObject({ type: 'table', header: expect.any(Array) });
});
it('also bounds a long quoted paragraph and keeps Unicode characters intact', () => {
  const text = 'A thought 🙂 '.repeat(4000);
  const blocks = noteBlocks('> ' + text);
  expect(blocks.length).toBeGreaterThan(10);
  expect(blocks.every((b) => b.type === 'blockquote')).toBe(true);
  expect(JSON.stringify(blocks)).not.toContain('�');
});
it('hides the generated goal-mirror comment while preserving comments inside code', () => {
  const blocks = noteBlocks('<!-- Generated by JARVIS from goal g123. Edits here are not read back. -->\n\n# Result\n\nA partial result.\n\n```html\n<!-- a code example -->\n```');
  expect(blocks.some((b) => b.type === 'html')).toBe(false);
  expect(blocks.some((b) => b.type === 'code' && b.text.includes('a code example'))).toBe(true);
  expect(blocks.some((b) => b.type === 'heading')).toBe(true);
});
