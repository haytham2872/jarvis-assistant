def test_one_card_is_posted_then_edited_in_place(world, cards):
    g = _start()
    run(_cycles())
    assert len(cards.posts) == 1
    assert cards.edits and all(mid == "m1" for mid, _ in cards.edits)
    assert "Done" in cards.edits[-1][1]
    assert S.card_id(g["goal_id"]) == "m1"


def test_an_unchanged_goal_is_not_edited_again(world, cards):
    g = _start()
    run(_cycles())
    n = len(cards.edits)
    run(R.refresh_card(g["goal_id"]))
    assert len(cards.edits) == n


def test_a_deleted_card_is_replaced_once(world, cards):
    g = _start()
    run(R.refresh_card(g["goal_id"]))
    cards.edit_result = "gone"
    S.transition(g["goal_id"], S.PAUSED, expect=(S.ACTIVE,))
    run(R.refresh_card(g["goal_id"]))
    assert len(cards.posts) == 2 and S.card_id(g["goal_id"]) == "m2"


def test_a_timed_out_post_never_becomes_a_second_card(world, cards):
    g = _start()
    cards.post_result = "uncertain"
    run(R.refresh_card(g["goal_id"]))
    S.transition(g["goal_id"], S.PAUSED, expect=(S.ACTIVE,))
    cards.post_result = "sent"
    run(R.refresh_card(g["goal_id"]))
    assert len(cards.posts) == 1 and S.card_id(g["goal_id"]) == "uncertain"


def test_a_failed_post_is_tried_again(world, cards):
    g = _start()
    cards.post_result = "failed"
    run(R.refresh_card(g["goal_id"]))
    cards.post_result = "sent"
    S.transition(g["goal_id"], S.PAUSED, expect=(S.ACTIVE,))
    run(R.refresh_card(g["goal_id"]))
    assert len(cards.posts) == 2 and S.card_id(g["goal_id"]) == "m2"


def test_a_post_cut_off_by_a_restart_is_uncertain_not_repeated(world, cards):
    g = _start()
    assert S.set_card(g["goal_id"], "pending", expect=None)
    S.recover()
    assert S.card_id(g["goal_id"]) == "uncertain"
    run(R.refresh_card(g["goal_id"]))
    assert cards.posts == []


def test_concurrent_refreshes_are_serialized_and_the_latest_wins(world, cards, monkeypatch):
    g = _start()
    run(R.refresh_card(g["goal_id"]))
    order = []

    async def slow_edit(mid, text):
        order.append(("start", text))
        await asyncio.sleep(0.01)
        order.append(("end", text))
        return "ok"
    R.set_card_functions(lambda t: None, slow_edit)

    async def two():
        S.transition(g["goal_id"], S.PAUSED, expect=(S.ACTIVE,))
        a = asyncio.create_task(R.refresh_card(g["goal_id"]))
        await asyncio.sleep(0)
        S.transition(g["goal_id"], S.ACTIVE, expect=(S.PAUSED,))
        b = asyncio.create_task(R.refresh_card(g["goal_id"]))
        await asyncio.gather(a, b)
    run(two())
    assert [k for k, _ in order] == ["start", "end", "start", "end"]   # never interleaved
    assert "Active" in order[-1][1]                                    # the latest state shown
